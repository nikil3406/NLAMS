import { NextResponse, type NextRequest } from 'next/server';
import { getCurrentUser } from '../../../../../lib/auth';
import { handleApiError } from '../../../../../lib/api-response';
import { acquisitionProposalService } from '../../../../../services/acquisition-proposals';

interface RouteContext {
  params: Promise<{ id: string }>;
}

/**
 * POST /api/acquisition-proposals/[id]/start-review
 * Transitions proposal from SUBMITTED to UNDER_REVIEW.
 * Only accessible by authorized Competent Authority user assigned to this proposal.
 */
export async function POST(
  request: NextRequest,
  context: RouteContext
): Promise<NextResponse> {
  try {
    const user = await getCurrentUser(request);
    if (!user) {
      return NextResponse.json(
        { success: false, error: 'Unauthorized' },
        { status: 401 }
      );
    }

    const { id } = await context.params;
    const updated = await acquisitionProposalService.startReview(id, user.id);

    return NextResponse.json(
      { success: true, data: updated },
      { status: 200 }
    );
  } catch (error) {
    return handleApiError(error);
  }
}
